"""Generate version-pinned entries for reviewed resource discovery, offline only."""
import hashlib
import runpy
import sys
from pathlib import Path

Image = runpy.run_path(str(Path(__file__).with_name('inspect-gi-functions.py')))['Image']
image = Image(sys.argv[1])
expected = '7F89938DA606C1281659607D464702CDDB9A09A7D4320A196630F60A811EC38E'
if hashlib.sha256(image.data).hexdigest().upper() != expected:
    raise SystemExit('Unreviewed executable')
entries = [0x14cfa10, 0x14c6760, 0x4b2210, 0x14c48c0,
           0x52f450, 0x19ccad20, 0x1441cc0, 0x14c90e0, 0x19febc0, 0x145bbf0, 0x14c7690, 0x98f830, 0x19fe800, 0x19fe8a0, 0x1438a36, 0x182aa7c, 0x182aac3, 0x19cb2fe0, 0x1439120, 0x1439146, 0x182a690, 0x182a6c3, 0x143a790, 0x143a7a8, 0x19e0b90, 0x19e2573, 0x19e2781, 0x19e2908, 0x19e0bb0, 0x12a8fb0, 0x976970, 0x19ff790, 0x19e8b20, 0x1599270, 0x1599870, 0x15999eb, 0x1599b67, 0x15a7030, 0x19ebd70, 0x19ebe30, 0x19ec43e, 0x145bb50, 0x6de1ae0, 0x7021590, 0x6e37aa0, 0x6e34e30, 0x7015f30, 0x710aa60, 0x710ac70]
lines = ['// CN 7.1 reviewed named lookup, reflection type and object enumeration.',
         '// Generated by scripts/generate-resource-profile.py; full build hash is verified by the observer.',
         'static bool resource_lookup_verified(uintptr_t base) {']
for rva in entries:
    data = image.read(rva, 32)
    if len(data) != 32 or not image.executable(rva):
        raise SystemExit('Invalid entry')
    lines += ['    { const uint8_t expected[32] = {' + ','.join(map(str, data)) + '}; uint8_t actual[32]{};',
              f'      if (!executable(base + {hex(rva)}, base) || !read_bytes(base + {hex(rva)}, actual, 32) || std::memcmp(expected, actual, 32)) return false; }}']
lines += ['    return true;', '}']
Path(sys.argv[2]).write_text('\n'.join(lines) + '\n', encoding='utf-8')

if len(sys.argv) > 3:
    trace = []
    for name, rva in [('FormatBytes', 0x15b9340), ('HashBytes', 0x145b710), ('FileLoadBytes',0x19d8ba0), ('MemoryLoadBytes',0x19d9030), ('CacheLoadBytes',0x19d95d0), ('TemplateLoadBytes',0x19d9660), ('InstanceBytes',0x19d97c0), ('RawCloneBytes',0x19e2510), ('MhyFileBytes',0x19f3dd0), ('AsyncTemplateBytes',0x19d9880), ('FinalizeBytes',0x19e2d10), ('ProviderBytes',0x6c1e400), ('ReadyBytes',0x19e0b90)]:
        data = image.read(rva, 32)
        trace.append('static constexpr uint8_t ' + name + '[32] = {' + ','.join(map(str, data)) + '};')
    Path(sys.argv[3]).write_text('\n'.join(trace) + '\n', encoding='utf-8')
