"""Emit the reviewed CN 7.2 core profile from the exact supplied executable/dump.

Requires capstone. Actor/resource research remains pinned to 7.1.
"""
import hashlib
import json
import runpy
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXE_SHA = '8B014F64B5DC12FBC476E0C362B053ABFDD7A1378CD282E4AD81057621DBD6B5'


def generate(executable, dump):
    Image = runpy.run_path(str(ROOT / 'scripts/inspect-gi-functions.py'))['Image']
    image = Image(executable)
    audit = json.loads((ROOT / 'docs/evidence/genshin-7.2-hierarchy-relocation.json').read_text(encoding='utf-8'))
    if hashlib.sha256(image.data).hexdigest().upper() != EXE_SHA:
        raise ValueError('Unreviewed executable')
    if hashlib.sha256(Path(dump).read_bytes()).hexdigest().upper() != audit['dumpSha256']:
        raise ValueError('Unreviewed metadata dump')
    # Resolved by named dump wrappers and their decoded call/jump targets.
    overrides = dict(
        NameA=0x1449820, NameB=0x14499a0, GetChild=0x1448ea0,
        ComponentGameObject=0x1464d40, GetActive=0x1463f90,
        RotationWorldCandidate=0x1a22a290, RotationLocalCandidate=0x1a22a430,
        SetLocalRotation=0x1448000, TimeScaleSet=0x1447a20,
        ComponentGetByName=0x1464eb0, BehaviourClassRegistration=0x1c25e37,
        MethodNameGet=0x4bbb60, MethodNameInitialize=0x531e50,
        ClassMethodSearch=0x51aa40, ClassMethodSearchCompare=0x51ab38,
        BehaviourEnabledGet=0x1a2008b0, BehaviourEnabledGetNative=0x10ee310,
        BehaviourEnabledSet=0x1a2008c0, BehaviourEnabledSetNative=0x10ee350,
        AnimatorUpdateModeGet=0x1a1fa480, AnimatorUpdateModeGetNative=0x11b1ee0,
        AnimatorIsHumanGet=0x1a1f9d70, AnimatorIsHumanGetNative=0x11b19e0,
        AnimatorAvatarGet=0x1a1fc4d0, AnimatorAvatarGetNative=0x11b45e0,
        RendererBonesGet=0x1a20e120, RendererMeshGet=0x1a20e1a0,
        RendererMeshGetNative=0x98b2a0, MeshBindPosesGet=0x1a213e60,
        MeshBindPosesGetNative=0x985460, AvatarBoneIndexGet=0x1a1fd090,
        AvatarBoneIndexGetNative=0x11b6150, LocalPositionGet=0x1a2273b0,
        LocalPositionGetNative=0x1447bc0, LocalPositionSet=0x1a227470,
        LocalPositionSetNative=0x1447c10, LocalScaleGet=0x1a22aa80,
        LocalScaleGetNative=0x1447da0, WorldPositionGet=0x1a229e70,
        WorldPositionSet=0x1a229eb0, WorldPositionGetNative=0x1447b30,
        WorldPositionSetNative=0x1447b80, WorldPositionRead=0x15d7d60,
        WorldPositionStore=0x15d7390, WorldRotationSet=0x1a22a320,
        WorldRotationSetNative=0x1447fc0, WorldRotationRead=0x15d7c70,
        WorldRotationStore=0x15d7170)
    lines = ['#pragma once', '#include <cstdint>',
             '// CN 7.2.0: offline reviewed; live validation is still required.',
             '// Generated by scripts/generate-gi72-profile.py.',
             '#if defined(GIMMD_ACTOR_TEMPLATES) || defined(GIMMD_ACTOR_SURVEY) || defined(GIMMD_RESOURCE_TRACE)',
             '#error CN 7.2 actor/resource interfaces have not been ported', '#endif',
             'namespace gimmd::hierarchy_profile {',
             'struct Entry { const char* name; uint32_t rva; uint8_t bytes[32]; };',
             f'inline constexpr char BuildSha256[] = "{EXE_SHA}";',
             'inline constexpr uint32_t ClassName = 0x70;',
             'inline constexpr unsigned MethodInvokerIndex = 2;',
             'inline constexpr uint32_t ClassMethodTable = 0x98, ClassMethodCount = 0xc2;',
             'inline constexpr uint32_t AnimatorCache = 0x57b3cd8, BehaviourCache = 0x57b4c18;',
             'inline constexpr Entry Entries[] = {']
    resolved = []
    for entry in audit['entries']:
        name = entry['name']
        if name in overrides:
            rva = overrides[name]
        elif len(entry['candidates']) == 1:
            rva = int(entry['candidates'][0]['rva'], 16)
        else:
            raise ValueError('Unresolved: ' + name)
        code = image.read(rva, 32)
        if len(code) != 32 or not image.executable(rva):
            raise ValueError('Invalid code: ' + name)
        lines.append('    {"' + name + '", ' + hex(rva) + ', {' + ','.join(map(str, code)) + '}},')
        resolved.append(dict(name=name, rva=hex(rva), bytes=code.hex()))
    lines += ['};', '}']
    (ROOT / 'src/generated/gi_hierarchy_profile.h').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    (ROOT / 'docs/evidence/genshin-7.2-core-profile.json').write_text(json.dumps(dict(
        executableSha256=EXE_SHA, dumpSha256=audit['dumpSha256'],
        liveValidated=False, entries=resolved), indent=2) + '\n', encoding='utf-8')


if __name__ == '__main__':
    generate(*sys.argv[1:])
